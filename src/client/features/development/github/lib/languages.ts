export const LANGUAGE_MATCH_LIMIT = 50
const FALLBACK_LANGUAGE_COLOR = '#94a3b8'

export function fuzzyMatchLanguages(query: string, limit = LANGUAGE_MATCH_LIMIT): GithubLanguage[] {
  const normalized = query.trim().toLowerCase()
  if (!normalized) return [...GITHUB_LANGUAGES]
  return GITHUB_LANGUAGES
    .filter((language) => language.name.toLowerCase().includes(normalized))
    .slice(0, Math.max(0, limit))
}

export function getLanguageColor(language: string | null | undefined): string {
  if (!language) return FALLBACK_LANGUAGE_COLOR
  return GITHUB_LANGUAGES.find((entry) => entry.name === language)?.color ?? FALLBACK_LANGUAGE_COLOR
}
