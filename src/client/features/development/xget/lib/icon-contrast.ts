const DARK_FOREGROUND = '#111827'
const LIGHT_FOREGROUND = '#ffffff'

function channel(value: number): number {
  const normalized = value / 255
  return normalized <= 0.03928 ? normalized / 12.92 : ((normalized + 0.055) / 1.055) ** 2.4
}

export function relativeLuminance(hex: string): number {
  const value = hex.replace('#', '')
  const red = Number.parseInt(value.slice(0, 2), 16)
  const green = Number.parseInt(value.slice(2, 4), 16)
  const blue = Number.parseInt(value.slice(4, 6), 16)
  return 0.2126 * channel(red) + 0.7152 * channel(green) + 0.0722 * channel(blue)
}

export function contrastRatio(foreground: string, background: string): number {
  const first = relativeLuminance(foreground)
  const second = relativeLuminance(background)
  const lighter = Math.max(first, second)
  const darker = Math.min(first, second)
  return (lighter + 0.05) / (darker + 0.05)
}

export function foregroundForHex(hex: string): string {
  const dark = contrastRatio(DARK_FOREGROUND, hex)
  const light = contrastRatio(LIGHT_FOREGROUND, hex)
  return dark >= light ? DARK_FOREGROUND : LIGHT_FOREGROUND
}
