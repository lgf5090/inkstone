export function NavIcon({ name, size = 16, className }: { name: string; size?: number; className?: string }) {
  if (isEmojiIcon(name)) {
    return <span aria-hidden className={cn('inline-flex items-center justify-center leading-none', className)} style={{ fontSize: size }}>{name}</span>
  }
  const Icon = ICONS[normalizeIconName(name)] ?? Folder
  return <Icon size={size} className={className} aria-hidden />
}
