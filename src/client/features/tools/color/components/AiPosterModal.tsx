import { useEffect, useRef, useState } from 'react'
import { CloudUpload, Download, Loader2 } from 'lucide-react'
import type { PoeticColorInterpretation } from '@shared/tools/color/types'
import { t } from '../../../../lib/i18n'
import { Modal } from '../../../../components/overlay'
import { Button } from '../../../../components/primitives'
import { useUi } from '../../../../store/ui'
import { colorApi } from '../api'

export interface AiPosterModalProps {
  open: boolean
  onClose: () => void
  imageSrc: string
  colors: string[]
  interpretations: PoeticColorInterpretation[]
  themeTitle?: string
}

export function AiPosterModal({
  open,
  onClose,
  imageSrc,
  colors,
  interpretations,
  themeTitle = 'Oriental Aesthetic Harmony',
}: AiPosterModalProps) {
  const canvasRef = useRef<HTMLCanvasElement | null>(null)
  const [isRendering, setIsRendering] = useState(true)
  const [isSavingToCloud, setIsSavingToCloud] = useState(false)

  // Render canvas poster card (1080 x 1440 resolution)
  useEffect(() => {
    if (!open || !imageSrc) return

    setIsRendering(true)
    const canvas = canvasRef.current
    if (!canvas) return
    const ctx = canvas.getContext('2d')
    if (!ctx) return

    const width = 1080
    const height = 1440
    canvas.width = width
    canvas.height = height

    const img = new Image()
    img.crossOrigin = 'anonymous'
    img.onload = () => {
      // 1. Background
      ctx.fillStyle = '#f8f8f7'
      ctx.fillRect(0, 0, width, height)

      // 2. Photo Area (Top with padding)
      const padX = 70
      const padTop = 70
      const photoWidth = width - padX * 2
      const photoHeight = 840

      ctx.save()
      // Rounded rect clip for image
      ctx.beginPath()
      ctx.roundRect(padX, padTop, photoWidth, photoHeight, 24)
      ctx.clip()

      // Cover scaling for the photo
      const imgRatio = img.width / img.height
      const frameRatio = photoWidth / photoHeight
      let sw = img.width
      let sh = img.height
      let sx = 0
      let sy = 0
      if (imgRatio > frameRatio) {
        sw = img.height * frameRatio
        sx = (img.width - sw) / 2
      } else {
        sh = img.width / frameRatio
        sy = (img.height - sh) / 2
      }
      ctx.drawImage(img, sx, sy, sw, sh, padX, padTop, photoWidth, photoHeight)
      ctx.restore()

      // 3. Typography: Theme Title
      ctx.fillStyle = '#1c1c1a'
      ctx.font = 'bold 38px "Noto Serif", serif, system-ui'
      ctx.textAlign = 'left'
      ctx.fillText(themeTitle, padX, 980)

      // Subtitle
      ctx.fillStyle = '#737370'
      ctx.font = '22px sans-serif'
      ctx.fillText('Color Harmony Card · Palette Exploration', padX, 1020)

      // 4. Color Swatches Ribbon (Middle)
      const swatchTop = 1060
      const swatchH = 150
      const swatchGap = 16
      const totalWidth = photoWidth
      const count = Math.max(1, colors.length)
      const swatchW = (totalWidth - swatchGap * (count - 1)) / count

      colors.forEach((hex, i) => {
        const x = padX + i * (swatchW + swatchGap)
        const interp = interpretations[i]

        // Swatch block
        ctx.fillStyle = hex
        ctx.beginPath()
        ctx.roundRect(x, swatchTop, swatchW, swatchH, 16)
        ctx.fill()

        // Swatch border
        ctx.strokeStyle = 'rgba(0,0,0,0.08)'
        ctx.lineWidth = 2
        ctx.stroke()

        // Label under swatch: Poetic name
        ctx.fillStyle = '#1c1c1a'
        ctx.font = 'bold 22px "Noto Serif", serif, system-ui'
        ctx.textAlign = 'center'
        const labelName = interp?.name || `Color ${i + 1}`
        ctx.fillText(labelName, x + swatchW / 2, swatchTop + swatchH + 40)

        // Label under swatch: HEX
        ctx.fillStyle = '#737370'
        ctx.font = '18px monospace'
        ctx.fillText(hex.toUpperCase(), x + swatchW / 2, swatchTop + swatchH + 72)
      })

      // 5. Footer Watermark
      ctx.fillStyle = '#a8a8a5'
      ctx.font = '18px sans-serif'
      ctx.textAlign = 'center'
      ctx.fillText('Generated by Inkstone Color Assistant', width / 2, 1370)

      setIsRendering(false)
    }

    img.src = imageSrc
  }, [open, imageSrc, colors, interpretations, themeTitle])

  const handleDownload = () => {
    const canvas = canvasRef.current
    if (!canvas) return
    const url = canvas.toDataURL('image/png')
    const a = document.createElement('a')
    a.href = url
    a.download = `color-poster-${Date.now()}.png`
    a.click()
  }

  const handleSaveToR2 = async () => {
    const canvas = canvasRef.current
    if (!canvas) return
    setIsSavingToCloud(true)
    try {
      const dataUrl = canvas.toDataURL('image/png')
      const asset = await colorApi.uploadAsset({
        assetType: 'palette_poster',
        fileFormat: 'png',
        data: dataUrl,
      })
      useUi.getState().toast({
        title: `Wallpaper saved to cloud R2 (${asset.id})`,
        tone: 'success',
      })
      onClose()
    } catch (e: unknown) {
      const err = e as Error
      useUi.getState().toast({
        title: err.message || 'Failed to save to cloud',
        tone: 'danger',
      })
    } finally {
      setIsSavingToCloud(false)
    }
  }

  return (
    <Modal
      open={open}
      onClose={onClose}
      title={t('tools.color.image.generate_poster')}
      width={680}
      footer={
        <div className="flex items-center justify-between w-full">
          <Button variant="secondary" size="sm" onClick={onClose}>
            {t('tools.color.common.cancel')}
          </Button>
          <div className="flex items-center gap-2">
            <Button
              variant="secondary"
              size="sm"
              disabled={isRendering || isSavingToCloud}
              onClick={handleSaveToR2}
              aria-label={t('tools.color.image.save_to_r2')}
            >
              {isSavingToCloud ? (
                <Loader2 size={14} className="animate-spin" />
              ) : (
                <CloudUpload size={14} />
              )}
              <span>{t('tools.color.image.save_to_r2')}</span>
            </Button>
            <Button
              variant="primary"
              size="sm"
              disabled={isRendering}
              onClick={handleDownload}
              aria-label={t('tools.color.image.download')}
            >
              <Download size={14} />
              <span>{t('tools.color.image.download')}</span>
            </Button>
          </div>
        </div>
      }
    >
      <div className="flex flex-col items-center justify-center p-2 max-h-[70vh] overflow-y-auto">
        {isRendering && (
          <div className="flex items-center gap-2 p-8 text-[var(--text-secondary)]">
            <Loader2 size={18} className="animate-spin text-[var(--accent)]" />
            <span>{t('tools.color.image.generating_poster')}</span>
          </div>
        )}
        <canvas
          ref={canvasRef}
          style={{ width: '100%', maxWidth: '480px', height: 'auto' }}
          className="rounded-[var(--r-md)] border border-[var(--border-subtle)] shadow-md"
        />
      </div>
    </Modal>
  )
}
