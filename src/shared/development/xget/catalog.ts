export type XgetPlatformKey = (typeof XGET_PLATFORMS)[number]['key']

export const XGET_PLATFORM_BY_KEY = Object.fromEntries(
  XGET_PLATFORMS.map((platform) => [platform.key, platform]),
) as Record<XgetPlatformKey, XgetPlatform>

export const XGET_PLATFORM_KEYS = XGET_PLATFORMS.map((platform) => platform.key)

export function xgetPathPrefix(key: string): string {
  return key.replace(/-/g, '/')
}

export function xgetCategoryOf(key: string): XgetCategory | null {
  return XGET_PLATFORM_BY_KEY[key as XgetPlatformKey]?.category ?? null
}

export const XGET_PLATFORMS_BY_LONGEST_PREFIX = [...XGET_PLATFORMS].sort(
  (a, b) => xgetPathPrefix(b.key).length - xgetPathPrefix(a.key).length,
)
