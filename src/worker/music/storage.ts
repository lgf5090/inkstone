/**
 * R2 storage for the music library.
 *
 * Uploads and downloads never name a path: every key is derived here from the account id, a track id
 * and the format, which is why an object can only land under the `music/` prefix this deployment
 * backs up. The ledger that pays for these bytes lives in `MusicStore`; a write that would cross the
 * account quota is refused under a lease so two concurrent finalizations cannot both see room.
 *
 * Deleting through `deleteMusicObjects` is strict: a failed R2 delete is queued on the music cleanup
 * table before the error is rethrown, so the maintenance sweep retries it and the caller is not told
 * a deletion happened when the bytes are still there.
 */
import {
  MUSIC_LIMITS,
  musicCoverKey,
  musicObjectKey,
  type MusicFormat,
} from '@shared/music/constants'
import { MUSIC_QUALITIES, type MusicQuality } from '@shared/music/model'
import type { Env } from '../env'
import { ApiError } from '../lib/errors'
import { isValidId } from '../lib/id'
import { acquireLease, type LeaseRelease } from '../lib/lease'
import type { MusicQuota, MusicStore } from './store'

export type MusicStorage = 'r2'

/**
 * Audio and video objects can be replaced under the same track id (a download changes quality), so
 * the browser must revalidate instead of trusting an immutable URL. R2 answers the conditional read
 * with 304 when nothing changed.
 */
export const MUSIC_AUDIO_CACHE_CONTROL = 'private, max-age=0, must-revalidate'
/** Covers are replaced under the same key, so the browser must revalidate; R2 supplies the ETag. */
export const MUSIC_COVER_CACHE_CONTROL = 'private, max-age=0, must-revalidate'
/** Holding the quota lease across a multipart completion needs room for a slow R2 round trip. */
export const MUSIC_QUOTA_LEASE_MS = 2 * 60 * 1000

export interface MusicObjectStream {
  body: ReadableStream<Uint8Array>
  /** The size R2 reports for this read; a range caller already knows the length it asked for. */
  size: number | null
  contentType: string | null
  etag: string | null
}

export interface MusicObjectPutOptions {
  contentType: string
  cacheControl?: string
  userId: string
  trackId: string
  kind: 'track' | 'cover'
  sha256?: string
}

export interface MusicObjectHead {
  size: number
  contentType: string | null
  customMetadata: Record<string, string> | null
  etag: string | null
}

/** The only object storage the music app uses. A KV-only deployment has no music upload surface. */
export function selectMusicStorage(env: Env): MusicStorage | null {
  return env.FILES ? 'r2' : null
}

export function hasMusicStorage(env: Env): boolean {
  return selectMusicStorage(env) === 'r2'
}

export function requireMusicStorage(env: Env): MusicStorage {
  if (!env.FILES) {
    throw new ApiError(
      503,
      'music_storage_unavailable',
      'Music storage requires the R2 binding (FILES). This deployment cannot store music files.',
    )
  }
  return 'r2'
}

export function requireMusicBucket(env: Env): R2Bucket {
  requireMusicStorage(env)
  return env.FILES!
}

/**
 * The key for one audio or video object. Both ids are generated by this worker and validated here,
 * so a caller cannot smuggle a path segment into the key.
 */
export function musicObjectKeyFor(input: {
  format: MusicFormat
  userId: string
  trackId: string
  quality: MusicQuality | string
}): string {
  if (!isValidId(input.userId) || !isValidId(input.trackId)) {
    throw new Error('invalid music object identity')
  }
  if (!(MUSIC_QUALITIES as readonly string[]).includes(input.quality)) {
    throw new Error('invalid music object quality')
  }
  return musicObjectKey({
    format: input.format,
    userId: input.userId,
    trackId: input.trackId,
    quality: input.quality,
  })
}

/** The key for a cover; the extension comes from the sniffed image type, not from a filename. */
export function musicCoverKeyFor(input: { userId: string; trackId: string; extension: string }): string {
  if (!isValidId(input.userId) || !isValidId(input.trackId)) {
    throw new Error('invalid music cover identity')
  }
  return musicCoverKey(input)
}

/** Write one small object (a cover, or a test fixture) with the metadata the stream route reads back. */
export async function putMusicObject(
  env: Env,
  key: string,
  bytes: Uint8Array,
  options: MusicObjectPutOptions,
): Promise<void> {
  if (!key.startsWith('music/')) throw new Error('music object keys must live under the music/ prefix')
  const bucket = requireMusicBucket(env)
  const customMetadata: Record<string, string> = {
    userId: options.userId,
    trackId: options.trackId,
    kind: options.kind,
  }
  if (options.sha256) customMetadata.sha256 = options.sha256
  await bucket.put(key, bytes, {
    httpMetadata: {
      contentType: options.contentType,
      cacheControl: options.cacheControl ?? (options.kind === 'cover'
        ? MUSIC_COVER_CACHE_CONTROL
        : MUSIC_AUDIO_CACHE_CONTROL),
    },
    customMetadata,
  })
}

/** Stream a file body into R2 without holding a second full copy in the isolate. */
export async function putMusicObjectStream(
  env: Env,
  key: string,
  body: ReadableStream<Uint8Array>,
  options: MusicObjectPutOptions,
): Promise<void> {
  if (!key.startsWith('music/')) throw new Error('music object keys must live under the music/ prefix')
  const bucket = requireMusicBucket(env)
  const customMetadata: Record<string, string> = {
    userId: options.userId,
    trackId: options.trackId,
    kind: options.kind,
  }
  if (options.sha256) customMetadata.sha256 = options.sha256
  await bucket.put(key, body, {
    httpMetadata: {
      contentType: options.contentType,
      cacheControl: options.cacheControl ?? (options.kind === 'cover'
        ? MUSIC_COVER_CACHE_CONTROL
        : MUSIC_AUDIO_CACHE_CONTROL),
    },
    customMetadata,
  })
}

export async function headMusicObject(env: Env, key: string): Promise<MusicObjectHead | null> {
  const bucket = requireMusicBucket(env)
  const object = await bucket.head(key)
  if (!object) return null
  return {
    size: object.size,
    contentType: object.httpMetadata?.contentType ?? null,
    customMetadata: object.customMetadata ?? null,
    etag: object.httpEtag ?? null,
  }
}

export async function readMusicObjectRange(
  env: Env,
  key: string,
  offset: number,
  length: number,
): Promise<MusicObjectStream | null> {
  if (length <= 0) return null
  const bucket = requireMusicBucket(env)
  const object = await bucket.get(key, { range: { offset, length } })
  return object ? toMusicObjectStream(object) : null
}

export async function readMusicObjectStream(env: Env, key: string): Promise<MusicObjectStream | null> {
  const bucket = requireMusicBucket(env)
  const object = await bucket.get(key)
  return object ? toMusicObjectStream(object) : null
}

/**
 * Delete objects after their rows are gone.
 *
 * The cleanup insert happens before the throw: the caller sees the failure, and the sweep still owns
 * the key. A queue insert that itself fails is logged, but the original delete error is what reaches
 * the caller, because that is the operation that did not happen.
 */
export async function deleteMusicObjects(
  env: Env,
  store: MusicStore,
  keys: readonly string[],
): Promise<void> {
  const unique = [...new Set(keys.filter((key) => key.length > 0))]
  if (!unique.length) return
  const bucket = requireMusicBucket(env)
  try {
    await bucket.delete(unique)
  } catch (error) {
    try {
      await store.queueCleanup(unique)
    } catch (queueError) {
      console.error('[inkstone] Music object cleanup could not be queued:', queueError)
    }
    throw new Error(`Failed to delete ${unique.length} music object(s); the cleanup queue will retry`, {
      cause: error,
    })
  }
}

/**
 * Best-effort variant for rollback paths where the caller is already reporting a failure. The queue
 * insert still happens inside `deleteMusicObjects`; only the throw is reduced to a warning.
 */
export async function discardMusicObjects(
  env: Env,
  store: MusicStore,
  keys: readonly string[],
): Promise<boolean> {
  try {
    await deleteMusicObjects(env, store, keys)
    return true
  } catch (error) {
    // The user-facing operation already failed; the cleanup row is the durable part.
    console.warn('[inkstone] Music object discard will retry from the cleanup queue:', error)
    return false
  }
}

/**
 * Serialize one quota check (and, for a completion, the ledger write that follows it).
 *
 * `incomingBytes` is the ledger size about to be added. The callback runs while the lease is held,
 * so two multipart completions cannot both observe the same free space and overshoot the ceiling.
 */
export async function withMusicQuotaLease<T>(
  env: Env,
  store: MusicStore,
  incomingBytes: number,
  run: (usage: MusicQuota) => Promise<T>,
  options: { waitMs?: number } = {},
): Promise<T> {
  let release: LeaseRelease | null = null
  const deadline = Date.now() + Math.max(0, options.waitMs ?? 0)
  // Background finalizers may wait for the single lease instead of failing their whole task; an
  // interactive request passes no wait and answers the conflict immediately.
  while (!release) {
    try {
      release = await acquireLease(
        env.DB,
        `music-quota:${store.userId}`,
        MUSIC_QUOTA_LEASE_MS,
        'Another music upload is being finalized. Try again shortly',
      )
    } catch (error) {
      if (!(error instanceof ApiError) || error.status !== 409 || Date.now() >= deadline) throw error
      await new Promise((resolve) => setTimeout(resolve, 50))
    }
  }
  try {
    const usage = await store.quotaUsage()
    if (incomingBytes > 0 && usage.bytes + incomingBytes > MUSIC_LIMITS.quotaBytes) {
      throw musicQuotaExceeded()
    }
    return await run(usage)
  } finally {
    await release()
  }
}

/**
 * Check room without writing anything.
 *
 * This deliberately does not take the finalize lease: parallel slices and upload inits may all look
 * at the same snapshot. The write itself is re-checked under the lease at completion, which is what
 * keeps the quota from being spent twice.
 */
export async function assertMusicQuota(store: MusicStore, incomingBytes: number): Promise<void> {
  const usage = await store.quotaUsage()
  if (incomingBytes > 0 && usage.bytes + incomingBytes > MUSIC_LIMITS.quotaBytes) {
    throw musicQuotaExceeded()
  }
}

function musicQuotaExceeded(): ApiError {
  const gigabytes = Math.round(MUSIC_LIMITS.quotaBytes / (1024 * 1024 * 1024))
  return new ApiError(
    413,
    'music_quota_exceeded',
    `The account music storage quota of ${gigabytes} GB has been reached`,
  )
}

function toMusicObjectStream(object: R2ObjectBody): MusicObjectStream {
  return {
    body: object.body as ReadableStream<Uint8Array>,
    size: object.size,
    contentType: object.httpMetadata?.contentType ?? null,
    etag: object.httpEtag ?? null,
  }
}
